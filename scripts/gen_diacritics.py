#!/usr/bin/env python3
"""Generate lua/mdrender/diacritics.lua from the Unicode Character Database.

The Kitty graphics protocol encodes the row and column of an image placeholder
cell with combining characters. Its specification defines the list as: the
characters of Unicode 6.0.0 with general category Mn, combining class 230 and
no decomposition mapping, in code point order, leaving out characters that may
fuse with a base character under normalization.

This script builds that list directly from UnicodeData.txt (Unicode License).

    python3 scripts/gen_diacritics.py
"""
import pathlib
import urllib.request

URL = "https://www.unicode.org/Public/6.0.0/ucd/UnicodeData.txt"
# Characters left out because they can fuse with other characters.
EXCLUDED = [
    "0300", "0301", "0302", "0303", "0304", "0306", "0307", "0308", "0309",
    "030A", "030B", "030C", "030F", "0311", "0313", "0314", "0342", "0653", "0654",
]
OUT = pathlib.Path(__file__).resolve().parent.parent / "lua" / "mdrender" / "diacritics.lua"


def main():
    data = urllib.request.urlopen(URL).read().decode("ascii")
    points = []
    for line in data.splitlines():
        # Category Mn, combining class 230, bidi class NSM, empty decomposition.
        if "Mn;230;NSM;;" not in line:
            continue
        if any(code in line for code in EXCLUDED):
            continue
        points.append(line.split(";")[0])
    rows = [", ".join("0x" + p for p in points[i:i + 10]) for i in range(0, len(points), 10)]
    OUT.write_text(
        "-- Row and column diacritics for Kitty Unicode image placeholders.\n"
        "-- Generated by scripts/gen_diacritics.py from UnicodeData.txt (Unicode 6.0.0).\n"
        "return {\n" + "".join("  " + r + ",\n" for r in rows) + "}\n"
    )
    print(f"{len(points)} code points written to {OUT}")


if __name__ == "__main__":
    main()
